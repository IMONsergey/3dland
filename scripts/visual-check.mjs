import {chromium} from 'playwright-core'
import {strict as assert} from 'node:assert'
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox','--disable-webgl','--disable-gpu']})
const base=process.env.SITE_URL||'http://127.0.0.1:4317/3dland/'
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[]
page.on('pageerror',err=>errors.push(err.message))
const resp=await page.goto(base,{waitUntil:'domcontentloaded',timeout:30000})
assert.equal(resp.status(),200)
await page.locator('.photo-stage').waitFor()
assert.equal(await page.locator('canvas').count(),0,'3D should lazy-load after entering exploration')
await page.locator('.era-button').nth(1).click()
assert.equal(await page.locator('.era-button.active').innerText(),'2035')
await page.locator('.primary-action').click()
await page.locator('.journey').waitFor()
assert.equal((await page.locator('.journey-kicker').innerText()).replace(/\s+/g,' ').trim(),'01 / 04 ТЕХНОЛОГИИ')
await page.locator('.journey-controls button').nth(1).click()
assert((await page.locator('.journey-kicker').innerText()).startsWith('02 / 04'))
await page.locator('.journey-exit').click()
await page.locator('.journey').waitFor({state:'detached'})
await page.locator('.header-nav button').filter({hasText:'Атлас прогнозов'}).click()
await page.locator('.wb-root').waitFor()
assert.equal(await page.locator('.wb-node-link').count(),14)
await page.locator('.wb-navigation button').nth(1).click()
assert.equal(await page.locator('.wb-compare-column').count(),3)
await browser.close()
console.log(JSON.stringify({stage:true,year:true,journey:true,atlas:true,compare:true,errors}))
if(errors.length)process.exit(1)
